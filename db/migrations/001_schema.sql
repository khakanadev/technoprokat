-- 001_schema.sql — структура базы данных ИС «ТехноПрокат» (физическая модель, пункт 1.4.10)
-- Девять таблиц в третьей нормальной форме: 4 справочника, пользователи и 4 предметные сущности.

CREATE TABLE schema_migrations (
    version     text PRIMARY KEY,
    applied_at  timestamptz NOT NULL DEFAULT now()
);

-- Справочники ---------------------------------------------------------------

CREATE TABLE roles (
    id     smallint PRIMARY KEY,
    code   text NOT NULL UNIQUE,
    title  text NOT NULL
);

CREATE TABLE categories (
    id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

CREATE TABLE rental_statuses (
    id     smallint PRIMARY KEY,
    code   text NOT NULL UNIQUE,
    title  text NOT NULL
);

-- Правило перехода: отсутствие записи означает запрет перехода для роли
CREATE TABLE status_transitions (
    from_status_id  smallint NOT NULL REFERENCES rental_statuses (id) ON DELETE RESTRICT,
    to_status_id    smallint NOT NULL REFERENCES rental_statuses (id) ON DELETE RESTRICT,
    role_id         smallint NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    PRIMARY KEY (from_status_id, to_status_id, role_id),
    CHECK (from_status_id <> to_status_id)
);

-- Пользователи --------------------------------------------------------------

CREATE TABLE users (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email          text NOT NULL,
    password_hash  text NOT NULL,                 -- bcrypt: соль хранится внутри хеша
    full_name      text NOT NULL CHECK (length(trim(full_name)) > 0),
    phone          text CHECK (phone ~ '^\+?[0-9]{10,15}$'),
    role_id        smallint NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    is_active      boolean NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));

-- Предметные сущности -------------------------------------------------------

CREATE TABLE equipment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL CHECK (length(trim(name)) > 0),
    category_id   smallint NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    inventory_no  text NOT NULL UNIQUE,
    daily_price   numeric(10,2) NOT NULL CHECK (daily_price >= 0),
    deposit       numeric(10,2) NOT NULL DEFAULT 0 CHECK (deposit >= 0),
    condition     text NOT NULL DEFAULT 'ok' CHECK (condition IN ('ok', 'service', 'broken')),
    photo         text,                           -- имя файла фотографии в каталоге media
    is_active     boolean NOT NULL DEFAULT true
);

CREATE TABLE rentals (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    manager_id  uuid REFERENCES users (id) ON DELETE RESTRICT,   -- 0..1: назначается при подтверждении
    status_id   smallint NOT NULL REFERENCES rental_statuses (id) ON DELETE RESTRICT,
    date_from   date NOT NULL,
    date_to     date NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (date_to >= date_from)
);

-- Композиция: позиция не существует без аренды
CREATE TABLE rental_items (
    rental_id      bigint NOT NULL REFERENCES rentals (id) ON DELETE CASCADE,
    equipment_id   bigint NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    price_per_day  numeric(10,2) NOT NULL CHECK (price_per_day >= 0),   -- цена на момент аренды
    PRIMARY KEY (rental_id, equipment_id)
);

-- Композиция: история и комментарии принадлежат аренде
CREATE TABLE rental_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id   bigint NOT NULL REFERENCES rentals (id) ON DELETE CASCADE,
    author_id   uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    type        text NOT NULL CHECK (type IN ('status', 'comment')),
    text        text NOT NULL CHECK (length(trim(text)) > 0),
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Индексы (таблица 1.4.11) --------------------------------------------------

CREATE INDEX rentals_status_created_idx  ON rentals (status_id, created_at DESC);
CREATE INDEX rentals_client_created_idx  ON rentals (client_id, created_at DESC);
CREATE INDEX rentals_manager_status_idx  ON rentals (manager_id, status_id);
CREATE INDEX rentals_dates_idx           ON rentals (date_from, date_to);
CREATE INDEX equipment_category_active_idx ON equipment (category_id) WHERE is_active;
CREATE INDEX rental_items_equipment_idx  ON rental_items (equipment_id);
CREATE INDEX rental_events_rental_idx    ON rental_events (rental_id, created_at);

-- Записи истории не изменяются и не удаляются (ЗИ-10); каскадное удаление вместе с арендой разрешено
CREATE FUNCTION forbid_event_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Записи истории аренды не изменяются' USING ERRCODE = 'P0001';
END $$;

CREATE TRIGGER rental_events_no_update BEFORE UPDATE ON rental_events
    FOR EACH ROW EXECUTE FUNCTION forbid_event_update();
